def _n(path_key, *keys, default=None):
    m = load_json(C.REPORTS_DIR / f"metrics_{path_key}.json") or {}
    for k in keys:
        if not isinstance(m, dict):
            return default
        m = m.get(k, default)
    return m


def modules() -> list[dict]:
    n_perf = _n("performance", "n_rows", default=4244)
    n_drop = _n("dropout", "n_rows", default=4424)
    n_att = _n("attendance", "n_rows", default=3000)
    n_sen = _n("sentiment", "n_rows", default=12000)
    return [
        dict(key="performance", letter="A", icon="📘", name="Subject forecast", page="Subject_Forecast",
             question="Of the subjects this student registered for in semester 2, how many will they clear?",
             data=f"Real university records - {n_perf:,} students who registered for semester-2 subjects",
             real=True,
             inputs="Course, age, admission route, fees / dues / scholarship, semester-1 results, subjects registered for semester 2",
             output="Expected subjects cleared and the expected backlog (registered minus cleared)",
             model="MLP neural network (compared with Ridge, Random Forest, XGBoost and a 'no-model' guess)",
             kind="Neural network for table-like data"),
        dict(key="dropout", letter="B", icon="🚪", name="Dropout warning", page="Dropout_Warning",
             question="Will this student drop out, still be studying, or graduate?",
             data=f"The same real university records - {n_drop:,} students whose final outcome is known",
             real=True,
             inputs="Course, age, admission route, fees / dues / scholarship, semester-1 (and optionally semester-2) results",
             output="Three chances that add to 100%: drops out / still studying / graduates",
             model="MLP neural network (compared with Logistic Regression, Random Forest, XGBoost)",
             kind="Neural network for table-like data"),
        dict(key="attendance", letter="C", icon="🗓️", name="Attendance watch", page="Attendance_Watch",
             question="Judging by the first 8 weeks, will this student's attendance end below 75%?",
             data=f"SIMULATED - {n_att:,} made-up students generated by rules written in the code "
                  "(no public attendance data exists)",
             real=False,
             inputs="8 weeks of attendance %, assignments submitted and portal logins, plus distance from campus, part-time job, hostel, scholarship, semester, last semester's attendance",
             output="Chance that final attendance falls below 75%",
             model="BiLSTM (a network that reads week after week in order), compared with Logistic Regression, Random Forest, XGBoost, plain MLP",
             kind="Neural network for sequences"),
        dict(key="sentiment", letter="D", icon="💬", name="Feedback mood", page="Feedback_Mood",
             question="Is a student's comment positive, neutral or negative - and which words decided it?",
             data=f"Real Coursera course reviews - {n_sen:,} reviews (4,000 per mood; 1-2 stars = negative, 3 = neutral, 4-5 = positive)",
             real=True,
             inputs="Free text written by a student",
             output="Chance of negative / neutral / positive, with the deciding words highlighted",
             model="Embedding + BiLSTM neural network (DistilBERT can be added on Colab); compared with TF-IDF + Logistic Regression",
             kind="Neural network for text"),
    ]


def by_key(key: str) -> dict:
    return next(m for m in modules() if m["key"] == key)


